// The version of the game and its update history, shown in the corner of the title page (ui/VersionInfo.tsx).
// This file is the one place to change: the number on the screen is the newest entry's, so it cannot be left behind.
//
// When a fix or an update is published (before the build for the release):
//   1. Add an entry at the top of CHANGELOG (newest first).
//   2. Version: a.b.c. A new feature or a large update raises b (1.0.0 → 1.1.0); a small fix raises c (1.1.0 → 1.1.1).
//      a is raised only for a change that makes the game something else (decided case by case).
//   3. date: the day it goes live in production, in Japan time (YYYY-MM-DD): written before the build, then checked against the day
//      the deploy really went live (if that was another day, correct it, build and deploy again). Never a guessed date.
//   4. changes: what changed for the player, in a few short Japanese lines; only what that publication contains.
// The tests (changelog.test.ts) check the order, the numbers and the dates. package.json's "version" (0.0.0) is not used.

export interface Release {
  /** a.b.c */
  version: string
  /** the day of the publication in production, Japan time (YYYY-MM-DD) */
  date: string
  /** what changed, for the player */
  changes: string[]
}

